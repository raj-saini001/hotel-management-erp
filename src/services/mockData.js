export const initStorage = () => {
  if (!localStorage.getItem('hotel_bookings')) {
    localStorage.setItem('hotel_bookings', JSON.stringify(INITIAL_BOOKINGS));
  }
  if (!localStorage.getItem('hotel_admins')) {
    localStorage.setItem('hotel_admins', JSON.stringify(INITIAL_ADMINS));
  }
  if (!localStorage.getItem('hotel_activity_logs')) {
    localStorage.setItem('hotel_activity_logs', JSON.stringify(INITIAL_ACTIVITY_LOGS));
  }
  if (!localStorage.getItem('hotel_settings')) {
    localStorage.setItem('hotel_settings', JSON.stringify(HOTEL_INFO));
  }
};

export const getStorageItem = (key, fallback = []) => {
  try {
    initStorage();
    const item = localStorage.getItem(key);
    return item ? JSON.parse(item) : fallback;
  } catch (e) {
    console.error(`Error reading ${key} from storage`, e);
    return fallback;
  }
};

export const setStorageItem = (key, value) => {
  try {
    localStorage.setItem(key, JSON.stringify(value));
  } catch (e) {
    console.error(`Error saving ${key} to storage`, e);
  }
};
